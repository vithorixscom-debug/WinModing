function detect() {
  const stored = localStorage.getItem(KEY);
  if (stored === "ru" || stored === "en") return stored;
  return String(navigator.language || "").toLowerCase().startsWith("ru") ? "ru" : "en";
}

export const locale = ref(detect());

export const localeOptions = [
  { id: "ru", label: "Русский" },
  { id: "en", label: "English" },
];

export function setLocale(tag) {
  locale.value = tag === "ru" ? "ru" : "en";
  localStorage.setItem(KEY, locale.value);
  document.documentElement.lang = locale.value;
}

export function t(key, vars = {}) {
  const pack = messages[locale.value] || messages.en;
  let text = pack[key] || messages.en[key] || key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

if (typeof document !== "undefined") {
  document.documentElement.lang = locale.value;
}

export function useI18n() {
  const translate = computed(() => {
    const current = locale.value;
    return (key, vars = {}) => {
      const pack = messages[current] || messages.en;
      let text = pack[key] || messages.en[key] || key;
      for (const [name, value] of Object.entries(vars)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
      return text;
    };
  });
  return { locale, t: translate, setLocale, localeOptions };
}
